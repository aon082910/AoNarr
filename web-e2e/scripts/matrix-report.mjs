#!/usr/bin/env node
// Builds .tmp/matrix-findings.md from the results of a full 28-project run (reads only files under .tmp/ and baselines/).
//   node scripts/matrix-report.mjs [--results .tmp/results.json] [--out .tmp/matrix-findings.md] [--wall "mm:ss"]
// Facts only: every number comes from a file the sweep wrote (results.json, smoke/axe/tabwalk records). Judgements are added by hand below the generated part.
import fs from "node:fs";
import path from "node:path";
import { E2E_DIR, TMP_DIR } from "./_common.mjs";

const args = process.argv.slice(2);
const opt = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
const resultsFile = path.resolve(E2E_DIR, opt("--results", ".tmp/results.json"));
const outFile = path.resolve(E2E_DIR, opt("--out", ".tmp/matrix-findings.md"));
const wall = opt("--wall", "");

const DESIGNS = ["classic", "midnight", "aurora", "ember", "noir", "paper", "terminal"];
const SPECS = ["smoke", "screenshot", "axe", "tabwalk"];
const readJson = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const exists = (f) => fs.existsSync(f);

// ---- results.json: status per project / spec / route --------------------------------------------------------------
const results = readJson(resultsFile);
const rows = []; // {project, spec, route, status, durationMs, error}
// First `n` non-empty lines of an error message with ANSI colour codes removed.
const ANSI = new RegExp(String.fromCharCode(27) + "\\[[0-9;]*m", "g");
const firstLine = (msg, n = 1) => msg.replace(ANSI, "").split(/\r?\n/).filter(Boolean).slice(0, n).join(" ").slice(0, 300);
function walk(suite, trail) {
  const here = suite.title && !/\.spec\.ts$/.test(suite.title) ? [...trail, suite.title] : trail;
  for (const sp of suite.specs ?? []) {
    for (const t of sp.tests ?? []) {
      const last = t.results?.[t.results.length - 1];
      const firstFail = (t.results ?? []).find((r) => r.status !== "passed" && r.error);
      rows.push({
        project: t.projectName, spec: sp.title, route: here[here.length - 1] ?? "?", status: last?.status ?? "unknown", durationMs: last?.duration ?? 0,
        error: firstLine(last?.error?.message ?? ""), flaky: t.status === "flaky",
        firstError: firstLine(firstFail?.error?.message ?? "", 2), attempts: (t.results ?? []).length,
        annotations: (t.annotations ?? []).map((a) => a.type),
      });
    }
  }
  for (const c of suite.suites ?? []) walk(c, here);
}
for (const s of results.suites) walk(s, []);
const projects = [...new Set(rows.map((r) => r.project))].sort();
const stats = results.stats ?? {};

// ---- per-test records --------------------------------------------------------------------------------------------
function rec(kind, project, route) {
  const f = path.join(TMP_DIR, kind, project, `${route}.json`);
  return exists(f) ? readJson(f) : null;
}
const routes = [...new Set(rows.map((r) => r.route))];
const partsOf = (p) => { const [design, theme, viewport] = p.split("-"); return { design, theme, viewport }; };
const classicOf = (p) => { const { theme, viewport } = partsOf(p); return `classic-${theme}-${viewport}`; };

const md = [];
const out = (s = "") => md.push(s);
const fmtMs = (ms) => `${Math.floor(ms / 60000)}m ${Math.round((ms % 60000) / 1000)}s`;

out(`# Phase 0 matrix findings (all 28 projects, full sweep)`);
out();
out(`Generated by \`scripts/matrix-report.mjs\` from \`.tmp/results.json\` and the per-route records the specs write (\`.tmp/smoke|axe|tabwalk|inventory\`). Everything below is **observed** in that run unless a line says "inferred". Classic is the reference for axe and Tab-walk comparisons (same theme and viewport, same run).`);
out();
out(`* Run started: ${stats.startTime ?? "?"}; Playwright duration ${stats.duration ? fmtMs(stats.duration) : "?"}${wall ? `; measured wall clock ${wall}` : ""}`);
out(`* Tests: ${rows.length} (expected ${stats.expected ?? "?"}, unexpected ${stats.unexpected ?? "?"}, flaky ${stats.flaky ?? "?"}, skipped ${stats.skipped ?? "?"}), ${projects.length} projects, ${routes.length} routes`);
out();

// ---- 1. pass / fail table ------------------------------------------------------------------------------------------
out(`## 1. Pass / fail per project and spec`);
out();
out(`Blocking = Classic projects only (screenshots vs baseline, axe and Tab-walk vs their ratchets). Redesign projects fail only on the smoke checks and, for axe/Tab-walk, never (report-only) unless E2E_STRICT_RATCHETS=1.`);
out();
out(`| project | smoke | screenshots | axe | tab-walk | total |`);
out(`|---|---|---|---|---|---|`);
const cell = (list) => { const p = list.filter((r) => r.status === "passed").length; const f = list.length - p; return list.length ? (f ? `${p} pass / **${f} fail**` : `${p} pass`) : "-"; };
for (const p of projects) {
  const mine = rows.filter((r) => r.project === p);
  const tp = mine.filter((r) => r.status === "passed").length;
  out(`| ${p} | ${SPECS.map((s) => cell(mine.filter((r) => r.spec === s))).join(" | ")} | ${tp}/${mine.length} |`);
}
out();
out(`Per design (sum of its 4 projects):`);
out();
out(`| design | smoke fail | screenshots fail | axe fail | tab-walk fail | total pass |`);
out(`|---|---|---|---|---|---|`);
for (const d of DESIGNS) {
  const mine = rows.filter((r) => partsOf(r.project).design === d);
  const f = (s) => mine.filter((r) => r.spec === s && r.status !== "passed").length;
  out(`| ${d} | ${f("smoke")} | ${f("screenshot")} | ${f("axe")} | ${f("tabwalk")} | ${mine.filter((r) => r.status === "passed").length}/${mine.length} |`);
}
out();

// ---- 2. failures by message ---------------------------------------------------------------------------------------
out(`## 2. Failing tests grouped by first error line`);
out();
const failed = rows.filter((r) => r.status !== "passed" && !r.flaky);
const byMsg = new Map();
for (const r of failed) {
  const key = `${r.spec} | ${r.error.replace(/\d{2,}/g, "N").slice(0, 160)}`;
  (byMsg.get(key) ?? byMsg.set(key, []).get(key)).push(r);
}
if (!failed.length) out(`No failing test.`);
for (const [k, list] of [...byMsg.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, 25)) {
  const ex = list.slice(0, 3).map((r) => `${r.route} [${r.project}]`).join("; ");
  out(`* **${list.length}x** ${k}  \n  e.g. ${ex}`);
}
out();

// ---- 2b. flaky tests (passed on a retry) and environment stalls -----------------------------------------------------
out(`## 2b. Tests that passed only on a retry, and environment stalls`);
out();
const flaky = rows.filter((r) => r.flaky);
const stallLike = (e) => /goto|Timeout|never mounted|never went quiet|did not settle|network level|ERR_/i.test(e);
const flakyStall = flaky.filter((r) => stallLike(r.firstError));
const flakyOther = flaky.filter((r) => !stallLike(r.firstError));
out(`* Flaky (failed first, passed on retry): ${flaky.length}; of these ${flakyStall.length} fit the loopback-stall pattern (navigation/network/settle errors) and ${flakyOther.length} do not.`);
for (const r of flakyOther.slice(0, 15)) out(`  * NOT stall-like: ${r.spec} ${r.route} [${r.project}]: ${r.firstError}`);
const gated = rows.filter((r) => r.annotations.includes("app-gate") || r.annotations.includes("navigation-retry"));
out(`* Tests that waited on the app-origin gate or retried a navigation: ${gated.length}`);
out();

// ---- 3. per design structural findings ----------------------------------------------------------------------------
out(`## 3. Structural findings per design`);
out();
const norm = (t) => String(t).replace(/\/[0-9a-f]{32,}/g, "/:token").replace(/\/\d+/g, "/:id").replace(/\s+/g, " ").slice(0, 160);
for (const d of DESIGNS) {
  const dProjects = projects.filter((p) => partsOf(p).design === d);
  out(`### ${d}`);
  out();
  // smoke records
  const smoke = [];
  for (const p of dProjects) for (const r of routes) { const s = rec("smoke", p, r); if (s) smoke.push({ p, r, s }); }
  const viol = new Map();
  for (const { p, r, s } of smoke) for (const v of s.violations ?? []) { const k = `${v.kind}: ${norm(v.text)}`; (viol.get(k) ?? viol.set(k, new Set()).get(k)).add(`${r} [${p}]`); }
  const settleFail = rows.filter((r) => partsOf(r.project).design === d && r.spec === "smoke" && r.status !== "passed");
  out(`* Smoke records read: ${smoke.length}. Failing smoke tests: ${settleFail.length}. Distinct violations: ${viol.size}.`);
  for (const [k, set] of [...viol.entries()].sort((a, b) => b[1].size - a[1].size).slice(0, 6)) out(`  * ${k}  (${set.size} route/project pair(s); e.g. ${[...set].slice(0, 3).join(", ")})`);
  // overflow
  const over = smoke.filter(({ s }) => s.overflow && s.overflow.scrollWidth > s.overflow.innerWidth);
  out(`* Horizontal overflow: ${over.length} route/project pair(s).`);
  for (const { p, r, s } of over.sort((a, b) => b.s.overflow.overflowPx - a.s.overflow.overflowPx).slice(0, 6)) out(`  * ${r} [${p}] +${s.overflow.overflowPx}px, widest ${s.overflow.offenders?.[0]?.selector ?? "?"}`);
  // clipped text (only present when the probe was in the run)
  const clip = smoke.filter(({ s }) => s.clipped && s.clipped.count > 0);
  if (smoke.some(({ s }) => s.clipped)) {
    out(`* Clipped text (heuristic: overflow hidden/clip, no ellipsis or line-clamp, content wider/taller than its box): ${clip.length} route/project pair(s), ${clip.reduce((a, { s }) => a + s.clipped.count, 0)} element(s).`);
    for (const { p, r, s } of clip.sort((a, b) => b.s.clipped.count - a.s.clipped.count).slice(0, 5)) out(`  * ${r} [${p}] ${s.clipped.count}: ${s.clipped.samples?.[0]?.selector ?? "?"} "${(s.clipped.samples?.[0]?.text ?? "").slice(0, 50)}"`);
  }
  // axe vs Classic
  let axeTotal = 0, axeClassic = 0, pairs = 0;
  const axeWorse = [];
  for (const p of dProjects) for (const r of routes) {
    const a = rec("axe", p, r), c = rec("axe", classicOf(p), r);
    if (!a || !c) continue;
    pairs++; axeTotal += a.totalNodes; axeClassic += c.totalNodes;
    if (d === "classic") continue;
    for (const [rule, n] of Object.entries(a.counters)) { const base = c.counters[rule] ?? 0; if (n > base) axeWorse.push({ p, r, rule, base, n, delta: n - base }); }
  }
  if (d === "classic") out(`* axe: ${pairs} route/project pairs, ${axeTotal} violating nodes in total (this is the reference).`);
  else {
    out(`* axe vs Classic (same theme+viewport): ${pairs} pairs, ${axeTotal} nodes vs ${axeClassic} for Classic (${axeTotal - axeClassic >= 0 ? "+" : ""}${axeTotal - axeClassic}); ${axeWorse.length} rule/route/project entries worse than Classic.`);
    const byRule = new Map();
    for (const w of axeWorse) { const e = byRule.get(w.rule) ?? { delta: 0, n: 0, ex: w }; e.delta += w.delta; e.n++; if (w.delta > e.ex.delta) e.ex = w; byRule.set(w.rule, e); }
    for (const [rule, e] of [...byRule.entries()].sort((a, b) => b[1].delta - a[1].delta).slice(0, 5)) out(`  * ${rule}: +${e.delta} nodes over ${e.n} route/project pair(s); worst ${e.ex.r} [${e.ex.p}] ${e.ex.base} -> ${e.ex.n}`);
  }
  // tab-walk vs Classic
  const tw = [];
  for (const p of dProjects) for (const r of routes) {
    const t = rec("tabwalk", p, r), c = rec("tabwalk", classicOf(p), r);
    if (!t) continue;
    tw.push({ p, r, t, c });
  }
  const sum = (k) => tw.reduce((a, { t }) => a + (t.counters[k] ?? 0), 0);
  const sumC = (k) => tw.reduce((a, { c }) => a + (c?.counters?.[k] ?? 0), 0);
  out(`* Tab-walk (${tw.length} walks): noIndicator ${sum("noIndicator")} (Classic ${sumC("noIndicator")}), bgOnlyIndicator ${sum("bgOnlyIndicator")} (${sumC("bgOnlyIndicator")}), obscuredByFixed ${sum("obscuredByFixed")} (${sumC("obscuredByFixed")}), coveredOrClipped ${sum("coveredOrClipped")} (${sumC("coveredOrClipped")}), trap ${sum("trap")} (${sumC("trap")}), unreachable ${sum("unreachable")} (${sumC("unreachable")}), focusedNotInteractive ${sum("focusedNotInteractive")} (${sumC("focusedNotInteractive")}), blockedMutations ${sum("blockedMutations")} (${sumC("blockedMutations")}).`);
  if (d !== "classic") {
    const worse = [];
    for (const { p, r, t, c } of tw) for (const k of ["noIndicator", "bgOnlyIndicator", "obscuredByFixed", "coveredOrClipped", "trap", "unreachable", "focusedNotInteractive"]) { const base = c?.counters?.[k] ?? 0; if ((t.counters[k] ?? 0) > base) worse.push({ p, r, k, base, n: t.counters[k] }); }
    for (const w of worse.sort((a, b) => (b.n - b.base) - (a.n - a.base)).slice(0, 6)) out(`  * ${w.r} [${w.p}] ${w.k}: Classic ${w.base} -> ${w.n}`);
    const ex = tw.flatMap(({ p, r, t }) => (t.stops ?? []).filter((s) => s.indicator === null || (s.strong === false)).map((s) => ({ p, r, s }))).slice(0, 0);
    void ex;
  }
  out();
}

// ---- 4. slowest / flakiest ------------------------------------------------------------------------------------------
out(`## 4. Timing`);
out();
const bySpec = (s) => rows.filter((r) => r.spec === s);
for (const s of SPECS) { const l = bySpec(s); out(`* ${s}: ${l.length} tests, mean ${(l.reduce((a, r) => a + r.durationMs, 0) / Math.max(1, l.length) / 1000).toFixed(1)} s, max ${(Math.max(0, ...l.map((r) => r.durationMs)) / 1000).toFixed(1)} s`); }
out();

fs.writeFileSync(outFile, md.join("\n") + "\n");
console.log(`wrote ${outFile} (${md.length} lines)`);
